#!/usr/bin/env python3
"""Solver benchmark harness: run the pipeline, append a record to a JSONL
results file, and regenerate a markdown comparison table.

Compare only runs with the same --workers and --max-time, use --repeat 2 or
more, and compare against the row whose label ends in "-baseline".
"""

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

SECTIONS = {
    "solver": "solver_settings",
    "hard": "hard_constraints",
    "soft": "soft_constraints",
    "section": "section_settings",
}

COLUMNS = [
    ("date", "date"), ("label", "label"), ("sha", "git_sha"), ("status", "status"),
    ("time s", "solve_time_s"), ("objective", "objective"), ("gap %", "gap_pct"),
    ("seats", "enrollments"), ("seated %", "seated_pct"), ("stu-conf", "student_conflicts"),
    ("room/fac-conf", None), ("grad-unmet", "grad_critical_unmet"),
    ("vars", "model_vars"), ("constraints", "model_constraints"),
]


def parse_override(s: str) -> tuple[list[str], object]:
    key, sep, raw = s.partition("=")
    if not sep or not key:
        raise ValueError(f"override must be KEY=VALUE: {s!r}")
    try:
        value = json.loads(raw)
    except ValueError:
        value = raw
    return key.split("."), value


def apply_overrides(config, overrides: list[tuple[list[str], object]]) -> None:
    for path, value in overrides:
        if path[0] not in SECTIONS or len(path) < 2:
            raise ValueError(f"override key must start with one of {sorted(SECTIONS)}: {path}")
        d = getattr(config, SECTIONS[path[0]])
        for part in path[1:-1]:
            d = d.setdefault(part, {})
        d[path[-1]] = value


def write_record(path: Path, record: dict) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a") as f:
        f.write(json.dumps(record, default=str) + "\n")


def load_records(path: Path) -> list[dict]:
    path = Path(path)
    if not path.exists():
        return []
    return [json.loads(ln) for ln in path.read_text().splitlines() if ln.strip()]


def _fmt(v) -> str:
    if v is None:
        return "-"
    if isinstance(v, float):
        return f"{v:.1f}"
    return str(v)


HEADER = """# Solver benchmark results

Generated by `scripts/benchmark_solver.py` from the results JSONL; do not edit.

## How to run

    .venv/bin/python scripts/benchmark_solver.py --label my-change --repeat 2 \\
        --override solver.linearization_level=2

## Comparison protocol

- Compare only runs with the same `--workers` and `--max-time`.
- Use `--repeat 2` at minimum; solver runs are noisy.
- Compare against the row with the same label suffix `-baseline`.

"""


def render_markdown(records: list[dict]) -> str:
    lines = [
        "| " + " | ".join(c[0] for c in COLUMNS) + " |",
        "|" + "|".join("---" for _ in COLUMNS) + "|",
    ]
    for r in records:
        cells = []
        for name, key in COLUMNS:
            if name == "date":
                v = str(r.get("timestamp") or "")[:16].replace("T", " ") or None
            elif name == "room/fac-conf":
                rc, fc = r.get("room_conflicts"), r.get("faculty_conflicts")
                v = None if rc is None and fc is None else f"{_fmt(rc)}/{_fmt(fc)}"
            else:
                v = r.get(key)
            cells.append(_fmt(v))
        lines.append("| " + " | ".join(cells) + " |")
    return HEADER + "\n".join(lines) + "\n"


def _git(*args: str) -> str | None:
    try:
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True,
                              check=True).stdout.strip()
    except Exception:
        return None


def run_once(args, overrides) -> dict:
    import ortools
    from sqlmodel import select

    from src.core.conflicts import ConflictMatrix
    from src.core.demand import DemandCalculator
    from src.core.engine import SchedulerConfig, SchedulingEngine
    from src.core.graph import PrerequisiteGraph
    from src.core.ingest import DataIngestor
    from src.core.validate import check_schedule_conflicts
    from src.database.connection import DatabaseManager
    from src.database.models import (
        ScheduleVersion,
        Section,
        SectionEnrollment,
        StudentDemand,
    )

    tmp = Path(tempfile.mkdtemp(prefix="gradimize-bench-"))
    try:
        t0 = time.time()
        db = DatabaseManager(tmp / "benchmark.db")
        db.reset_database()
        with db.get_session() as session:
            DataIngestor(session, Path(args.data_dir)).load_all(Path(args.time_slots))
            graph = PrerequisiteGraph(session)
            DemandCalculator(session, graph).calculate_all_demands()
            matrix = ConflictMatrix(session)
            matrix.build_matrix()

            config = SchedulerConfig.load_default()
            apply_overrides(config, overrides)
            config.solver_settings["max_time_seconds"] = args.max_time
            config.solver_settings["num_workers"] = args.workers

            engine = SchedulingEngine(session, matrix, config)
            sections = engine.create_sections(args.semester)
            result = engine.solve(sections, args.label, args.semester)
            pipeline_time = time.time() - t0
            stats = result.stats or {}

            sv = session.exec(select(ScheduleVersion).order_by(ScheduleVersion.id.desc())).first()
            sid = sv.id if sv else None
            best_bound = ((sv.solver_stats or {}).get("best_objective_bound") if sv else None)

            demands = list(session.exec(select(StudentDemand)).all())
            sec_course = {s.id: s.course_code for s in session.exec(
                select(Section).where(Section.schedule_id == sid)).all()}
            seated = {(e.student_id, sec_course[e.section_id]) for e in session.exec(
                select(SectionEnrollment)).all() if e.section_id in sec_course}
            crit = [d for d in demands if d.is_graduation_critical]
            unmet = sum(1 for d in crit if (d.student_id, d.course_code) not in seated)
            rep = check_schedule_conflicts(session, sid) if sid is not None else None
            n_enr = len(result.enrollments)

            return {
                "timestamp": datetime.now().isoformat(timespec="seconds"),
                "label": args.label,
                "git_sha": _git("rev-parse", "--short", "HEAD") or "unknown",
                "git_dirty": bool(_git("status", "--porcelain")),
                "overrides": {k: v for k, v in (
                    (".".join(p), val) for p, val in overrides)},
                "max_time": args.max_time,
                "workers": args.workers,
                "nproc": os.cpu_count(),
                "ortools_version": ortools.__version__,
                "semester": args.semester,
                "n_sections_created": len(sections),
                "status": result.status,
                "objective": result.objective_value,
                "best_bound": best_bound,
                "gap_pct": stats.get("optimality_gap_pct"),
                "solve_time_s": result.solve_time_seconds,
                "pipeline_time_s": round(pipeline_time, 2),
                "sections_scheduled": len(result.sections),
                "enrollments": n_enr,
                "meetings": len(result.meetings),
                "two_phase": stats.get("two_phase"),
                "model_vars": stats.get("model_vars"),
                "model_constraints": stats.get("model_constraints"),
                "sectioning": stats.get("sectioning"),
                "demands_total": len(demands),
                "seated_pct": round(n_enr / len(demands) * 100, 1) if demands else None,
                "grad_critical_total": len(crit),
                "grad_critical_unmet": unmet,
                "room_conflicts": rep.room if rep else None,
                "faculty_conflicts": rep.faculty if rep else None,
                "student_conflicts": rep.student if rep else None,
            }
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def print_summary(r: dict) -> None:
    print("-" * 60)
    print(f"{r['label']}  sha={r['git_sha']}{'+dirty' if r['git_dirty'] else ''}  "
          f"status={r['status']}")
    print(f"  objective={_fmt(r['objective'])} bound={_fmt(r['best_bound'])} "
          f"gap%={_fmt(r['gap_pct'])}")
    print(f"  solve={_fmt(r['solve_time_s'])}s pipeline={_fmt(r['pipeline_time_s'])}s "
          f"vars={_fmt(r['model_vars'])} constraints={_fmt(r['model_constraints'])}")
    print(f"  sections={r['sections_scheduled']}/{r['n_sections_created']} "
          f"seats={r['enrollments']} seated%={_fmt(r['seated_pct'])}")
    print(f"  conflicts: student={_fmt(r['student_conflicts'])} room={_fmt(r['room_conflicts'])} "
          f"faculty={_fmt(r['faculty_conflicts'])}  grad-unmet="
          f"{r['grad_critical_unmet']}/{r['grad_critical_total']}")


def parse_args(argv: list[str]) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Run the solver pipeline, append a record to a JSONL file and "
                    "regenerate a markdown table. Uses a temporary database.")
    p.add_argument("--max-time", type=int, default=120)
    p.add_argument("--workers", type=int, default=8)
    p.add_argument("--label", default="adhoc")
    p.add_argument("--results", type=Path, default=Path("benchmarks/results.jsonl"))
    p.add_argument("--md", type=Path, default=Path("benchmarks/RESULTS.md"))
    p.add_argument("--data-dir", default="data/sample")
    p.add_argument("--time-slots", default="config/time_slots.yaml")
    p.add_argument("--semester", default="2026FA")
    p.add_argument("--repeat", type=int, default=1)
    p.add_argument("--override", action="append", default=[], metavar="KEY=VALUE",
                   help="dotted key (solver|hard|soft|section).path=json-value; repeatable")
    return p.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(sys.argv[1:] if argv is None else argv)
    try:
        overrides = [parse_override(s) for s in args.override]
    except ValueError as e:
        print(e)
        return 2
    for _ in range(args.repeat):
        record = run_once(args, overrides)
        write_record(args.results, record)
        print_summary(record)
    args.md.parent.mkdir(parents=True, exist_ok=True)
    args.md.write_text(render_markdown(load_records(args.results)))
    print(f"Table: {args.md}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
